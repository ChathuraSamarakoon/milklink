export async function searchNearbyFarmersApi(params: FarmerSearchParams): Promise<FarmerSearchResult[]> {
  // Simulate network roundtrip
  await new Promise((resolve) => setTimeout(resolve, 350));

  return ALL_DEMO_FARMERS.filter((f) => {
    // Distance within radius
    const withinRadius = f.distanceKm <= params.radiusKm;
    // Quantity available meets or reasonably fulfills requested litres
    const hasLitres = f.availableLitres >= params.litres * 0.8;
    // Organic filter if enabled
    const organicMatch = !params.organicOnly || f.organic;
    // Max price filter if enabled
    const priceMatch = !params.maxPrice || f.pricePerLitre <= params.maxPrice;

    return withinRadius && hasLitres && organicMatch && priceMatch;
  });
}
